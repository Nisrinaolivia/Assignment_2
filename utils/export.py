"""Builds a Word (.docx) version of the advice memo for download."""

import re
from datetime import date
from io import BytesIO

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor


def _add_formatted_text(paragraph, text):
    """Adds text to a paragraph, turning **bold** and *italic* markdown into Word formatting."""
    parts = re.split(r"(\*\*[^*]+\*\*|\*[^*]+\*)", text)
    for part in parts:
        if part.startswith("**") and part.endswith("**"):
            paragraph.add_run(part[2:-2]).bold = True
        elif part.startswith("*") and part.endswith("*") and len(part) > 2:
            paragraph.add_run(part[1:-1]).italic = True
        elif part:
            paragraph.add_run(part)


def _add_markdown(doc, markdown_text):
    """Converts simple markdown (headings, bullet/numbered lists, paragraphs) into Word content."""
    for raw in markdown_text.splitlines():
        line = raw.strip()
        if not line or line in ("---", "***"):
            continue
        heading = re.match(r"^(#{1,6})\s+(.*)", line)
        bullet = re.match(r"^[-*•]\s+(.*)", line)
        numbered = re.match(r"^\d+[.)]\s+(.*)", line)
        if heading:
            level = min(len(heading.group(1)) + 1, 4)
            doc.add_heading(heading.group(2).strip("* "), level=level)
        elif bullet:
            _add_formatted_text(doc.add_paragraph(style="List Bullet"), bullet.group(1))
        elif numbered:
            _add_formatted_text(doc.add_paragraph(style="List Number"), numbered.group(1))
        else:
            _add_formatted_text(doc.add_paragraph(), line)


def build_memo_docx(memo, conclusion, steps):
    """
    memo:       the memo text produced by the AI (markdown)
    conclusion: the final conclusion string
    steps:      list of (title, result_label, reasoning) tuples for the annex
    Returns the .docx file as bytes.
    """
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(11)

    title = doc.add_heading("Notifiable Data Breach Assessment", level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.LEFT

    meta = doc.add_paragraph()
    meta.add_run("Privacy Act 1988 (Cth), Part IIIC\n").italic = True
    meta.add_run(f"Date: {date.today().strftime('%d %B %Y')}")

    p = doc.add_paragraph()
    p.add_run("Conclusion: ").bold = True
    run = p.add_run(conclusion.upper() if conclusion else "NOT DETERMINED")
    run.bold = True
    run.font.color.rgb = RGBColor(0x1F, 0x4E, 0x79)

    doc.add_heading("Advice memo", level=1)
    _add_markdown(doc, memo)

    doc.add_heading("Annex: Step-by-step analysis", level=1)
    for step_title, label, reasoning in steps:
        doc.add_heading(step_title, level=2)
        r = doc.add_paragraph()
        r.add_run("Result: ").bold = True
        r.add_run(label)
        if isinstance(reasoning, list):
            for item in reasoning:
                doc.add_paragraph(str(item), style="List Bullet")
        elif reasoning:
            doc.add_paragraph(str(reasoning))

    note = doc.add_paragraph()
    note.add_run(
        "Generated by an AI-assisted student tool (LAWS90286, Melbourne Law School). "
        "Not legal advice. Must be reviewed by a qualified practitioner."
    ).italic = True

    buffer = BytesIO()
    doc.save(buffer)
    return buffer.getvalue()
