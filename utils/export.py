"""Builds Word (.docx) downloads: the advice memo and the draft s 26WK statement."""

import re
from datetime import date
from io import BytesIO

from docx import Document
from docx.shared import Pt, RGBColor

BLUE = RGBColor(0x1F, 0x4E, 0x79)
DISCLAIMER = ("Generated by an AI-assisted student tool (LAWS90286, Melbourne Law School). "
              "Not legal advice. Must be reviewed by a qualified practitioner.")


def _add_formatted_text(paragraph, text):
    """Adds text to a paragraph, turning **bold** and *italic* markdown into Word formatting."""
    parts = re.split(r"(\*\*[^*]+\*\*|\*[^*]+\*)", text)
    for part in parts:
        if part.startswith("**") and part.endswith("**"):
            paragraph.add_run(part[2:-2]).bold = True
        elif part.startswith("*") and part.endswith("*") and len(part) > 2:
            paragraph.add_run(part[1:-1]).italic = True
        elif part:
            paragraph.add_run(part)


def _add_markdown(doc, markdown_text, top_level=2):
    """Converts simple markdown (headings, bullet/numbered lists, paragraphs) into Word content."""
    for raw in (markdown_text or "").splitlines():
        line = raw.strip()
        if not line or line in ("---", "***"):
            continue
        heading = re.match(r"^(#{1,6})\s+(.*)", line)
        bullet = re.match(r"^[-*•]\s+(.*)", line)
        numbered = re.match(r"^\d+[.)]\s+(.*)", line)
        if heading:
            level = min(len(heading.group(1)) + top_level - 1, 4)
            doc.add_heading(heading.group(2).strip("* "), level=level)
        elif bullet:
            _add_formatted_text(doc.add_paragraph(style="List Bullet"), bullet.group(1))
        elif numbered:
            _add_formatted_text(doc.add_paragraph(style="List Number"), numbered.group(1))
        else:
            _add_formatted_text(doc.add_paragraph(), line)


def _new_document(title, subtitle):
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(11)
    doc.add_heading(title, level=0)
    meta = doc.add_paragraph()
    meta.add_run(subtitle + "\n").italic = True
    meta.add_run(f"Date: {date.today().strftime('%d %B %Y')}")
    return doc


def _finish(doc):
    doc.add_paragraph().add_run(DISCLAIMER).italic = True
    buffer = BytesIO()
    doc.save(buffer)
    return buffer.getvalue()


def build_memo_docx(memo, conclusion, steps, factors=None, sources=None):
    """
    memo:       the memo text produced by the AI (markdown)
    conclusion: the final conclusion string
    steps:      list of (title, result_label, reasoning) tuples for the annex
    factors:    optional list of s 26WG factor dicts (factor, finding, effect)
    sources:    optional list of OAIC passages relied on (dicts with page, section, subsection)
    Returns the .docx file as bytes.
    """
    doc = _new_document("Notifiable Data Breach Assessment", "Privacy Act 1988 (Cth), Part IIIC")

    p = doc.add_paragraph()
    p.add_run("Conclusion: ").bold = True
    run = p.add_run(conclusion.upper() if conclusion else "NOT DETERMINED")
    run.bold = True
    run.font.color.rgb = BLUE

    doc.add_heading("Advice memo", level=1)
    _add_markdown(doc, memo)

    doc.add_heading("Annex A: Step-by-step analysis", level=1)
    for step_title, label, reasoning in steps:
        doc.add_heading(step_title, level=2)
        r = doc.add_paragraph()
        r.add_run("Result: ").bold = True
        r.add_run(str(label))
        if isinstance(reasoning, list):
            for item in reasoning:
                if item:
                    doc.add_paragraph(str(item), style="List Bullet")
        elif reasoning:
            doc.add_paragraph(str(reasoning))

    if factors:
        doc.add_heading("Annex B: Serious harm factors (s 26WG)", level=1)
        table = doc.add_table(rows=1, cols=3)
        table.style = "Light Grid Accent 1"
        for cell, text in zip(table.rows[0].cells, ("Factor", "Finding", "Effect on risk")):
            cell.text = text
        for f in factors:
            row = table.add_row().cells
            row[0].text = str(f.get("factor", ""))
            row[1].text = str(f.get("finding", ""))
            row[2].text = str(f.get("effect", ""))

    if sources:
        doc.add_heading("Annex C: OAIC guidance relied on", level=1)
        doc.add_paragraph(
            "Office of the Australian Information Commissioner, Data breach preparation and response "
            "(July 2019), Part 4. Passages retrieved by the tool:"
        )
        seen = set()
        for s in sorted(sources, key=lambda x: x["page"]):
            key = (s["page"], s["section"], s["subsection"])
            if key in seen:
                continue
            seen.add(key)
            heading = s["section"] + (f" — {s['subsection']}" if s["subsection"] else "")
            doc.add_paragraph(f"p {s['page']}: {heading}", style="List Bullet")

    return _finish(doc)


def build_statement_docx(statement_md, entity_name):
    """The draft statement to the Commissioner under s 26WK."""
    doc = _new_document(
        "Draft statement about an eligible data breach",
        f"Privacy Act 1988 (Cth) s 26WK — {entity_name or 'entity'}",
    )
    note = doc.add_paragraph()
    note.add_run("DRAFT — complete all [to be confirmed] items before lodging with the OAIC.").bold = True
    _add_markdown(doc, statement_md, top_level=1)
    return _finish(doc)
